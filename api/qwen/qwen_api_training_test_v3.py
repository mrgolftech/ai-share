    def tokenize_count(self, text: str) -> Optional[int]:
        # 这里也使用统一重试逻辑，但不产生正式测试项。
        max_attempts = 1 + self.retries

        for attempt in range(1, max_attempts + 1):
            try:
                r = self.s.post(
                    self.url("/tokenize"),
                    headers=self.oh(),
                    json={
                        "model": self.model,
                        "prompt": text,
                        "add_special_tokens": False,
                    },
                    timeout=(
                        self.connect_timeout,
                        self.read_timeout,
                    ),
                    verify=self.verify_tls,
                )

                if (
                    r.status_code in RETRYABLE_HTTP_STATUS
                    and attempt < max_attempts
                ):
                    time.sleep(self.backoff_seconds(attempt, r))
                    continue

                if not (200 <= r.status_code < 300):
                    return None

                data = r.json()

                if isinstance(data.get("count"), int):
                    return data["count"]

                return len(data.get("tokens") or [])

            except Exception as exc:
                if (
                    self.should_retry_exception(exc)
                    and attempt < max_attempts
                ):
                    time.sleep(self.backoff_seconds(attempt))
                    continue
                return None

        return None

    def long_context(self) -> None:
        if not self.long_targets:
            return

        long_dir = self.out / "long_context"
        long_dir.mkdir(exist_ok=True)

        unit = (
            "这是长上下文测试固定段落。"
            "The quick brown fox jumps over the lazy dog. "
            "0123456789 ABCDEFGHIJKLMNOPQRSTUVWXYZ。\n"
        )

        for target in self.long_targets:
            if target >= self.context_len:
                self.skip(
                    f"long_context_{target}",
                    "Long Context",
                    "/v1/chat/completions",
                    (
                        "目标达到/超过 max_model_len；"
                        "需为模板和输出预留空间"
                    ),
                )
                continue

            repeats = max(10, target // 25)
            text = unit * repeats
            count = self.tokenize_count(text)

            for _ in range(3):
                if not count:
                    break

                ratio = target / count
                if 0.96 <= ratio <= 1.04:
                    break

                repeats = max(1, int(repeats * ratio))
                text = unit * repeats
                count = self.tokenize_count(text)

            fp = long_dir / f"target_{target}_actual_{count}.txt"
            fp.write_text(text, encoding="utf-8")

            body = {
                "model": self.model,
                "messages": [
                    {
                        "role": "user",
                        "content": text + "\n只回答：LONG_CONTEXT_OK",
                    }
                ],
                "temperature": 0,
                "max_tokens": 32,
                "chat_template_kwargs": {"enable_thinking": False},
            }

            def check(
                data: Any,
                _: requests.Response,
                target=target,
                count=count,
                fp=fp,
            ):
                text_out = (
                    data["choices"][0]["message"].get("content") or ""
                )
                ok = "LONG_CONTEXT_OK" in text_out
                return (
                    ok,
                    f"target={target}, tokenize_count≈{count}",
                    {
                        "target": target,
                        "count": count,
                        "prompt_file": fp.name,
                        "usage": data.get("usage"),
                    },
                )

            self.request(
                f"long_context_{target}",
                "Long Context",
                "POST",
                "/v1/chat/completions",
                body,
                self.oh(),
                check,
            )

            self.delay(self.heavy_cooldown)


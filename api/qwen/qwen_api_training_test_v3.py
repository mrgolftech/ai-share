    def status_of(self, name: str) -> Optional[str]:
        row = next((x for x in self.results if x.name == name), None)
        return row.status if row else None

    def group(self, names: list[str]) -> str:
        statuses = [self.status_of(name) for name in names]

        if all(x == "PASS" for x in statuses):
            return "PASS"

        if any(x == "PASS" for x in statuses):
            return "PARTIAL"

        if all(x in {None, "SKIP"} for x in statuses):
            return "NOT_TESTED"

        return "FAIL"


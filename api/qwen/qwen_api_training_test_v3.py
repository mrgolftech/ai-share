def now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def js(x: Any) -> str:
    return json.dumps(x, ensure_ascii=False, indent=2)


def script_sha256() -> str:
    try:
        return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    except Exception:
        return "unknown"


def sha_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def masked(secret: str) -> str:
    if not secret:
        return ""
    if len(secret) <= 8:
        return "***"
    return secret[:3] + "***" + secret[-3:]


def redact(obj: Any, secret: str) -> Any:
    """日志脱敏；大图片和长文本不重复落盘。"""
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k == "data" and isinstance(v, str) and len(v) > 1000:
                try:
                    raw = base64.b64decode(v)
                    out[k] = (
                        f"<BASE64_IMAGE_OMITTED bytes={len(raw)} "
                        f"sha256={sha_bytes(raw)}>"
                    )
                except Exception:
                    out[k] = f"<LARGE_DATA_OMITTED chars={len(v)}>"
            else:
                out[k] = redact(v, secret)
        return out

    if isinstance(obj, list):
        return [redact(v, secret) for v in obj]

    if isinstance(obj, str):
        text = obj.replace(secret, masked(secret)) if secret else obj

        if text.startswith("data:image/") and ";base64," in text:
            head, b64 = text.split(";base64,", 1)
            try:
                raw = base64.b64decode(b64)
                return (
                    f"{head};base64,<OMITTED bytes={len(raw)} "
                    f"sha256={sha_bytes(raw)}>"
                )
            except Exception:
                return f"{head};base64,<OMITTED chars={len(b64)}>"

        if len(text) > 30000:
            return (
                f"<LONG_TEXT_OMITTED chars={len(text)} sha256={sha_text(text)}>\n"
                f"HEAD:\n{text[:600]}\n...\nTAIL:\n{text[-600:]}"
            )
        return text

    return obj


def get_font(size: int = 54) -> ImageFont.ImageFont:
    candidates = [
        "C:/Windows/Fonts/arial.ttf",
        "C:/Windows/Fonts/calibri.ttf",
        "C:/Windows/Fonts/segoeui.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
        "/System/Library/Fonts/Supplemental/Arial.ttf",
    ]
    for p in candidates:
        try:
            if Path(p).exists():
                return ImageFont.truetype(p, size=size)
        except Exception:
            pass
    try:
        return ImageFont.truetype("DejaVuSans.ttf", size=size)
    except Exception:
        return ImageFont.load_default()



    def stream(
        self,
        name: str,
        category: str,
        ep: str,
        body: dict[str, Any],
        headers: dict[str, str],
        mode: str,
        events: Optional[list[str]] = None,
        markers: Optional[list[str]] = None,
        validate: Optional[
            Callable[[str], tuple[bool, str, dict[str, Any]]]
        ] = None,
    ) -> str:
        seq = self.next_seq()

        req = {
            "method": "POST",
            "url": self.url(ep),
            "headers": headers,
            "json": body,
        }

        max_attempts = 1 + self.retries
        attempts_log: list[dict[str, Any]] = []
        overall_start = time.perf_counter()

        final_raw: list[str] = []
        final_events: list[str] = []
        final_parts: list[str] = []
        final_code: Optional[int] = None
        final_first_content_ms: Optional[float] = None
        final_exception: Optional[BaseException] = None
        final_stream_file: Optional[Path] = None
        recovered = False

        for attempt in range(1, max_attempts + 1):
            raw: list[str] = []
            evs: list[str] = []
            parts: list[str] = []
            first_content_ms: Optional[float] = None
            attempt_start = time.perf_counter()
            code: Optional[int] = None

            try:
                with self.s.post(
                    self.url(ep),
                    headers=headers,
                    json=body,
                    stream=True,
                    timeout=(self.connect_timeout, self.read_timeout),
                    verify=self.verify_tls,
                ) as r:
                    code = r.status_code

                    if (
                        code in RETRYABLE_HTTP_STATUS
                        and attempt < max_attempts
                    ):
                        attempt_ms = round(
                            (time.perf_counter() - attempt_start) * 1000, 2
                        )
                        wait = self.backoff_seconds(attempt, r)
                        attempts_log.append(
                            {
                                "attempt": attempt,
                                "status_code": code,
                                "elapsed_ms": attempt_ms,
                                "received_stream_lines": 0,
                                "will_retry": True,
                                "backoff_seconds": wait,
                            }
                        )
                        print(
                            f"  ↳ {name}: SSE HTTP {code}，"
                            f"{wait:g}s 后重试 ({attempt}/{max_attempts})"
                        )
                        time.sleep(wait)
                        continue

                    for line in r.iter_lines(decode_unicode=True):
                        if line is None:
                            continue

                        raw.append(line)

                        if line.startswith("event:"):
                            evs.append(line.split(":", 1)[1].strip())
                            continue

                        if not line.startswith("data:"):
                            continue

                        payload = line.split(":", 1)[1].strip()
                        if payload == "[DONE]":
                            continue

                        try:
                            obj = json.loads(payload)
                        except Exception:
                            continue

                        piece = ""

                        if mode == "chat":
                            try:
                                piece = (
                                    obj["choices"][0]["delta"].get("content") or ""
                                )
                            except Exception:
                                pass

                        elif (
                            mode == "responses"
                            and obj.get("type") == "response.output_text.delta"
                        ):
                            piece = obj.get("delta") or ""

                        elif (
                            mode == "anthropic"
                            and obj.get("type") == "content_block_delta"
                        ):
                            delta = obj.get("delta") or {}
                            if delta.get("type") == "text_delta":
                                piece = delta.get("text") or ""

                        if piece:
                            if first_content_ms is None:
                                first_content_ms = round(
                                    (time.perf_counter() - attempt_start) * 1000,
                                    2,
                                )
                            parts.append(piece)

                attempt_ms = round(
                    (time.perf_counter() - attempt_start) * 1000, 2
                )
                attempts_log.append(
                    {
                        "attempt": attempt,
                        "status_code": code,
                        "elapsed_ms": attempt_ms,
                        "received_stream_lines": len(raw),
                        "received_text_chars": len("".join(parts)),
                    }
                )

                final_raw = raw
                final_events = evs
                final_parts = parts
                final_code = code
                final_first_content_ms = first_content_ms
                recovered = attempt > 1
                break

            except Exception as exc:
                attempt_ms = round(
                    (time.perf_counter() - attempt_start) * 1000, 2
                )
                received_any = bool(raw or evs or parts)
                retryable = self.should_retry_exception(exc) and not received_any

                attempts_log.append(
                    {
                        "attempt": attempt,
                        "status_code": code,
                        "elapsed_ms": attempt_ms,
                        "exception": f"{type(exc).__name__}: {exc}",
                        "received_stream_lines": len(raw),
                        "received_text_chars": len("".join(parts)),
                        "retryable": retryable,
                    }
                )

                # 无论是否重试，都保留该 attempt 的部分 SSE
                if raw:
                    attempt_file = (
                        self.streams
                        / f"{seq:02d}_{name}_attempt_{attempt}_partial.sse.txt"
                    )
                    attempt_file.write_text("\n".join(raw), encoding="utf-8")
                    attempts_log[-1]["partial_stream_file"] = attempt_file.name

                final_exception = exc
                final_raw = raw
                final_events = evs
                final_parts = parts
                final_code = code
                final_first_content_ms = first_content_ms

                if retryable and attempt < max_attempts:
                    wait = self.backoff_seconds(attempt)
                    attempts_log[-1]["will_retry"] = True
                    attempts_log[-1]["backoff_seconds"] = wait
                    print(
                        f"  ↳ {name}: SSE {type(exc).__name__} 且尚未收到有效流，"
                        f"{wait:g}s 后重试 ({attempt}/{max_attempts})"
                    )
                    time.sleep(wait)
                    continue

                # 一旦收到部分流，自动重试会把两次输出混在一起，所以直接停止。
                break

        total_ms = round((time.perf_counter() - overall_start) * 1000, 2)
        text = "".join(final_parts)
        raw_text = "\n".join(final_raw)

        if final_raw:
            final_stream_file = self.streams / f"{seq:02d}_{name}.sse.txt"
            final_stream_file.write_text(raw_text, encoding="utf-8")

        if final_code is None:
            notes = (
                f"{type(final_exception).__name__}: {final_exception}"
                if final_exception is not None
                else "SSE 未得到 HTTP Response"
            )
            status = "ERROR"
            facts: dict[str, Any] = {
                "events": final_events,
                "reconstructed_text": text,
            }

        else:
            required_events = events or []
            missing = [x for x in required_events if x not in final_events]
            marker_ok = (
                True
                if not markers
                else any(marker in raw_text for marker in markers)
            )

            ok = 200 <= final_code < 300 and not missing and marker_ok
            notes = "流式协议通过"
            facts = {
                "events": final_events,
                "reconstructed_text": text,
            }

            if ok and validate:
                try:
                    ok, notes, extra = validate(text)
                    facts.update(extra)
                except Exception as exc:
                    ok = False
                    notes = f"流式判定程序异常: {type(exc).__name__}: {exc}"
                    facts["checker_exception"] = True

            elif not ok:
                if final_code in {400, 401, 403, 404, 409, 422}:
                    notes = (
                        f"HTTP {final_code}，明确客户端/协议错误，不自动重试"
                    )
                else:
                    notes = (
                        f"缺少事件={missing} 或完成标记，"
                        f"HTTP={final_code}"
                    )

            status = "PASS" if ok else "FAIL"

        if recovered and status == "PASS":
            notes += f"；第 {len(attempts_log)} 次尝试恢复"

        resp_info = {
            "status_code": final_code,
            "elapsed_ms": total_ms,
            "first_content_ms": final_first_content_ms,
            "events": final_events,
            "reconstructed_text": text,
            "attempts": attempts_log,
            "recovered_by_retry": recovered,
            "raw_sse_file": final_stream_file.name if final_stream_file else None,
        }

        if final_exception is not None:
            resp_info["last_exception"] = (
                f"{type(final_exception).__name__}: {final_exception}"
            )

        rec = self.save(seq, name, req, resp_info, status, notes, facts)

        self.add(
            seq=seq,
            name=name,
            category=category,
            endpoint=ep,
            status=status,
            code=final_code,
            elapsed_ms=total_ms,
            ttft_ms=final_first_content_ms,
            attempts=len(attempts_log),
            recovered_by_retry=recovered and status == "PASS",
            notes=notes,
            record_file=rec,
            stream_file=final_stream_file,
            facts=facts,
        )

        self.delay()
        return text


def parse_targets(text: str) -> list[int]:
    if not text.strip():
        return []

    values = []
    for part in text.split(","):
        part = part.strip()
        if not part:
            continue

        value = int(part)
        if value <= 0:
            raise ValueError("long context target 必须 > 0")

        values.append(value)

    return values


